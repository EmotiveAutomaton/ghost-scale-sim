"""Shared plumbing for the experiment modules: CLI parsing, deterministic per-observer
seeding, and output paths. Kept deliberately small — each experiment owns its own design.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import struct
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

from ..config import Config, load_config


def default_workers() -> int:
    return max(1, (os.cpu_count() or 2) - 2)


def run_parallel(chunk_payloads: list, worker_fn, workers: int | None = None) -> list:
    """Run ``worker_fn(payload) -> list[record]`` over ``chunk_payloads`` and concatenate.

    ``worker_fn`` MUST be a module-level function (picklable). Observers are independent,
    so each payload typically covers one (cell, seed) chunk and builds its own model. With
    ``workers==1`` runs sequentially (used by --quick / tests / reproducibility)."""
    workers = default_workers() if workers is None else int(workers)
    if workers <= 1 or len(chunk_payloads) <= 1:
        out = []
        for payload in chunk_payloads:
            out.extend(worker_fn(payload))
        return out
    records: list = []
    with ProcessPoolExecutor(max_workers=workers) as ex:
        for recs in ex.map(worker_fn, chunk_payloads):
            records.extend(recs)
    return records

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "results"
FIGURES_DIR = REPO_ROOT / "figures"


def standard_argparser(description: str) -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=description)
    p.add_argument("--config", default=None, help="path to YAML config (default: config/default.yaml)")
    p.add_argument("--quick", action="store_true", help="fast smoke-scale run (dev)")
    p.add_argument("--seed", type=int, default=None, help="override base seed")
    p.add_argument("--out", default=None, help="override results output dir")
    p.add_argument("--workers", type=int, default=None,
                   help="parallel worker processes (default: cpu-2; 1 = sequential)")
    return p


def resolve_config(args) -> Config:
    cfg = load_config(path=args.config, quick=args.quick)
    if args.seed is not None:
        cfg.set("run.base_seed", int(args.seed))
    return cfg


# --------------------------------------------------------------------------- #
# Per-observer seeding. Two schemes, and which one is live is an explicit choice.
# --------------------------------------------------------------------------- #
SEED_SCHEME_ENV = "GHOSTSCALE_SEED_SCHEME"
DEFAULT_SEED_SCHEME = "hash"


def seed_scheme() -> str:
    """Which seeding scheme is live: ``hash`` (the default) or ``legacy``.

    Read from an environment variable rather than from the config because the experiment workers
    call ``observer_rng`` directly without a config in hand, and an environment variable is
    inherited by spawned worker processes on every platform this runs on.
    """
    return os.environ.get(SEED_SCHEME_ENV, DEFAULT_SEED_SCHEME).strip().lower()


def legacy_observer_seed(base_seed: int, cell_index: int, seed_rep: int, observer_i: int) -> int:
    """The original scheme. Retained, reachable, and NOT collision-resistant despite the old claim.

    A linear combination of primes is solvable, and at the cardinalities this project runs it
    collides heavily: 46,550 duplicate seeds in 96,000 slots on the overlap sweep, with the
    structure `cell c, seed s, reader i` colliding with `cell c+1, seed s-10, reader i+67`, because
    100003 - 10*10007 = -67.

    THE DIRECTION WAS MEASURED AND IS BENIGN, which is why the historical numbers stand: every
    collision is ACROSS cells and none is inside a single (cell, seed) group, which is the unit the
    between-reader statistics are computed over. Cross-cell collisions make comparisons partly
    paired, which correlates the errors and makes differences more precise rather than less.

    It is kept because every committed result before the repair pass was produced with it, and a
    record that cannot be regenerated by the code that produced it is not a record. Select it with
    ``GHOSTSCALE_SEED_SCHEME=legacy``.
    """
    return int((base_seed * 1_000_003
                + cell_index * 100_003
                + seed_rep * 10_007
                + observer_i) % (2**63 - 1))


def hashed_observer_seed(base_seed: int, cell_index: int, seed_rep: int, observer_i: int) -> int:
    """The default scheme: a cryptographic hash of the tuple, with no solvable collision structure.

    There is no small-integer solution to a SHA-256 collision the way there is to a linear
    combination, so the whole class is gone rather than pushed somewhere else. Verified
    collision-free on every envelope this project runs.
    """
    payload = struct.pack("<qqqq", int(base_seed), int(cell_index), int(seed_rep), int(observer_i))
    return int(struct.unpack("<Q", hashlib.sha256(payload).digest()[:8])[0] % (2 ** 63 - 1))


def observer_seed(base_seed: int, cell_index: int, seed_rep: int, observer_i: int) -> int:
    """Deterministic per-observer seed. Identical inputs give identical output (Spec §10).

    Dispatches on ``seed_scheme()``. The default changed in the repair pass, so every number
    produced after it differs from every number produced before it, deliberately and with both
    versions reported side by side.
    """
    if seed_scheme() == "legacy":
        return legacy_observer_seed(base_seed, cell_index, seed_rep, observer_i)
    return hashed_observer_seed(base_seed, cell_index, seed_rep, observer_i)


def observer_rng(base_seed: int, cell_index: int, seed_rep: int, observer_i: int) -> np.random.Generator:
    return np.random.default_rng(observer_seed(base_seed, cell_index, seed_rep, observer_i))


def ensure_dirs(out_dir: Path | None = None) -> tuple[Path, Path]:
    """Resolve (results_dir, figures_dir).

    An explicit ``--out`` redirects the FIGURES too, into ``<out>/figures``. Without this a
    run directed away from ``results/`` would still overwrite the committed figures — which is
    the failure it was invoked to avoid. (Learned the hard way: a ``--quick`` run without
    ``--out`` destroyed V2's E8 outputs; see DECISIONS_V3.md, "An incident worth recording".)
    """
    if out_dir is not None:
        res = Path(out_dir)
        figs = res / "figures"
    else:
        res, figs = RESULTS_DIR, FIGURES_DIR
    res.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    return res, figs
