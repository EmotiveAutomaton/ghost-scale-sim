"""R-6 and R-8a — an estimator for every parameter, and a map of where each one is measurable.

THE CORRECTION THIS ITEM RESTS ON. The diagnostics pass concluded trust was unidentifiable. It
fitted trust to the OBSERVATION TAPE, and the tape is generated by the world, which contains no
trust parameter. That is like inferring how much somebody trusts a newspaper by studying the
newspaper: the newspaper is the same whoever reads it, so nothing about it varies with the reader's
disposition and nothing about it can reveal one.

A reader's parameter has to be fitted to something the READER produces. Which raises the question
this module is organised around, and it is a modelling choice rather than a technical one.

-----------------------------------------------------------------------------------------
WHAT COUNTS AS OBSERVABLE. TWO STANDARDS, BOTH RUN, REPORTED AS A BRACKET.

  NARROW   what the reader DOES: how long it keeps looking, and what it finally says the work was
           for. An engagement trace and an answer. This is what an experiment on a person collects
           without asking them to introspect, and it is the conservative standard.

  WIDE     the same, plus a graded report of how sure it is across every possible purpose. Common
           in judgment research. It assumes the reader can read out its own internal state
           perfectly and report it honestly, which is a strong assumption sitting uncomfortably
           close to what this framework is about: the gap between what is in a work and what a
           reader can recover from it. Handing the reader a perfect channel to its own mind adds a
           second channel with no counterpart in the world being modelled.

Real readers are between the two. Narrow is a FLOOR on what is measurable and wide is a CEILING, so
the pair brackets the truth. Neither is primary in the code. Narrow is primary in the prose.

-----------------------------------------------------------------------------------------
WHAT SATURATION MEANS, BECAUSE IT IS NOT A MEASUREMENT FAILURE.

Under the narrow standard trust recovers up to a point and then stops. Above it, a reader trusting
the label at 0.7 and one trusting it at 0.99 do exactly the same things: same engagement, same
answer, every time. No experiment could distinguish them, because there is nothing to distinguish.
For every purpose the theory cares about they ARE the same reader, and "how much does this one
trust the label" stops being a question with an answer.

That threshold is not arbitrary. It is where the label's evidence per glance overtakes the work's,
which the channel-accounting check locates in closed form. Saturation is what a parameter looks like
once it has already won its argument.

So the output is not a verdict per parameter. It is a MAP: for each parameter, under each standard,
the range over which it is a measured quantity and the range over which it is a free choice.
"""
