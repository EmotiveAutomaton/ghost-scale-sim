# =========================================================================== #
# Behaviour, at both standards.
# =========================================================================== #
def _behaviour(kappa: float, artifacts, cfg: Config, n_timesteps: int, forced_k: int,
               D, standard: str) -> np.ndarray:
    """Run a reader at this trust over a fixed set of artifacts and return what is observable.

    The random stream is fixed per artifact and shared across candidate values, so two candidates
    see the same world and differ only in the reader. Stochastic action selection, because with
    deterministic selection the choice is a step function of the parameter and a fit has nothing to
    grip: the likelihood is degenerate almost everywhere.
    """
    from ..environment import Environment
    from ..exact import make_exact_agent
    from ..generative_model import build_shared_model
    from ..observer import rollout_observer

    c = cfg.copy()
    c.set("signal_model.kappa", float(kappa))
    c.set("inference.exact", True)
    c.set("agent.action_selection", "stochastic")
    gm = build_shared_model(c, kappa=float(kappa))
    env = Environment(c, gm, np.random.default_rng(4_242), honesty=1.0, signing_rate=1.0)

    parts = []
    for j, art in enumerate(artifacts):
        r = np.random.default_rng(9_100 + 37 * j)
        agent = make_exact_agent(gm, D, c, rng=r)
        res = rollout_observer(agent, art, env, c, r, n_timesteps, force_deep_k=forced_k)
        q = np.asarray(res.final_goal_posterior, dtype=float)
        if standard == "narrow":
            # What the reader DID: the engagement trace, and the answer it gave.
            answer = np.zeros(q.size)
            answer[int(np.argmax(q))] = 1.0
            parts.append(np.concatenate([np.asarray(res.attention, dtype=float), answer]))
        else:
            # The same, plus the graded confidence report.
            parts.append(np.concatenate([np.asarray(res.attention, dtype=float), q]))
    return np.concatenate(parts)


def _fit_kappa(true_kappa: float, artifacts, cfg: Config, grid, D, standard: str,
               n_timesteps: int, forced_k: int) -> float:
    target = _behaviour(true_kappa, artifacts, cfg, n_timesteps, forced_k, D, standard)
    losses = [float(np.mean((_behaviour(k, artifacts, cfg, n_timesteps, forced_k, D, standard)
                             - target) ** 2)) for k in grid]
    return float(grid[int(np.argmin(losses))])


def recover_kappa(cfg: Config, grid, seeds: int, n_artifacts: int = 16,
                  n_timesteps: int = 12, forced_k: int = 2) -> list:
    """Recover trust from the reader's own behaviour, at both observability standards."""
    from ..environment import Environment
    from ..generative_model import build_D, build_shared_model

    base = build_shared_model(cfg)
    D = build_D(cfg, np.random.default_rng(0))
    rows = []
    for standard in CR.OBSERVABILITY:
        for true_k in grid:
            ests = []
            for s in range(seeds):
                rng = np.random.default_rng(5_500 + 71 * s)
                env = Environment(cfg, base, np.random.default_rng(5_600 + s),
                                  honesty=0.6, signing_rate=1.0)
                arts = [env.make_artifact(
                    provenance=int(rng.integers(int(cfg.cardinalities.num_provenance))),
                    goal=int(rng.integers(int(cfg.cardinalities.num_goals))), rng=rng)
                    for _ in range(n_artifacts)]
                ests.append(_fit_kappa(float(true_k), arts, cfg, grid, D, standard,
                                       n_timesteps, forced_k))
            rows.append({
                "parameter": "kappa (trust in the label)", "standard": standard,
                "estimator": ("least squares on the reader's own behaviour: "
                              + ("engagement trace and answer"
                                 if standard == "narrow"
                                 else "engagement trace and graded confidence")),
                "fitted_to": "the reader", "true": float(true_k),
                "recovered_mean": float(np.mean(ests)),
                "recovered_sd": float(np.std(ests, ddof=1)) if len(ests) > 1 else 0.0,
                "recovered_sem": (float(np.std(ests, ddof=1) / np.sqrt(len(ests)))
                                  if len(ests) > 1 else 0.0),
                "n_seeds": seeds,
            })
    return rows


# =========================================================================== #
# The parameters that already had estimators, carried through unchanged so the map is complete.
# =========================================================================== #
def carry_forward_from_diagnostics() -> list:
    """omega, mu and the value gate, as the diagnostics pass measured them.

    Re-reported rather than re-run, because their estimators did not change and the point of the map
    is to put all four parameters on one page under one vocabulary. The two that were fitted by an
    ANALYST holding the correct model are marked as such, because that is a strictly easier question
    than whether the reader can identify the value, and for readability the gap between the two is
    the whole version 4 reframe.
    """
    from ..diagnostics import diagnostics_dir
    path = diagnostics_dir() / "p1_recovery.json"
    if not path.exists():
        return []
    v = json.loads(path.read_text(encoding="utf-8"))
    rows = []
    for r in v.get("recovery", []):
        if r["parameter"].startswith("kappa"):
            continue                      # superseded by the behavioural fit above
        fitted_to = ("the reader" if r["parameter"] == "mu" else "an analyst holding the model")
        rows.append({
            "parameter": {"omega": "omega (how readable the content is)",
                          "mu": "mu (depth of the maker's thinking)",
                          "theta (lambda)": "theta (the value-alignment gate)"}.get(
                              r["parameter"], r["parameter"]),
            "standard": "not applicable",
            "estimator": v["estimators"].get(r["parameter"], ""),
            "fitted_to": fitted_to,
            "true": r["true"], "recovered_mean": r["recovered_mean"],
            "recovered_sd": r["recovered_sd"], "recovered_sem": r["recovered_sem"],
            "n_seeds": r["n_seeds"],
        })
    return rows


# =========================================================================== #
def _map_one(rows: list, parameter: str, standard: str | None = None) -> dict:
    sub = [r for r in rows if r["parameter"] == parameter
           and (standard is None or r["standard"] == standard)]
    if len(sub) < 2:
        return {"parameter": parameter, "standard": standard, "assessable": False}
    t = np.array([r["true"] for r in sub], dtype=float)
    m = np.array([r["recovered_mean"] for r in sub], dtype=float)
    se = np.array([r["recovered_sem"] for r in sub], dtype=float)
    order = np.argsort(t)
    t, m, se = t[order], m[order], se[order]
    frac, flags = CR.identifiable_fraction(t, m, se)
    live = [f for f in flags if f["distinguishable"]]
    lo = float(min(f["from"] for f in live)) if live else float("nan")
    hi = float(max(f["to"] for f in live)) if live else float("nan")
    from ..diagnostics.criteria import spearman
    return {
        "parameter": parameter, "standard": standard, "assessable": True,
        "fitted_to": sub[0]["fitted_to"], "estimator": sub[0]["estimator"],
        "grid": t.tolist(), "recovered": m.tolist(),
        "rank_correlation": spearman(t, m),
        "slope": float(np.polyfit(t, m, 1)[0]) if np.ptp(t) > 0 else float("nan"),
        "identifiable_fraction": frac,
        "identifiable_from": lo, "identifiable_to": hi,
        "reading": CR.map_label(frac),
        "steps": flags,
    }


def run(cfg: Config, workers: int = 1, seeds: int = 6) -> dict:
    out = repair_dir("r6_estimators")
    grid = np.round(np.linspace(0.1, 0.9, 9), 3)
    rows = recover_kappa(cfg, grid, seeds) + carry_forward_from_diagnostics()
    pd.DataFrame(rows).to_csv(out / "recovery.csv", index=False)

    the_map = [_map_one(rows, "kappa (trust in the label)", "narrow"),
               _map_one(rows, "kappa (trust in the label)", "wide")]
    for name in ("omega (how readable the content is)", "mu (depth of the maker's thinking)",
                 "theta (the value-alignment gate)"):
        the_map.append(_map_one(rows, name))
    the_map = [m for m in the_map if m.get("assessable")]
    pd.DataFrame([{k: v for k, v in m.items() if not isinstance(v, (list, dict))}
                  for m in the_map]).to_csv(out / "identifiability_map.csv", index=False)

    narrow = next((m for m in the_map if m["parameter"].startswith("kappa")
                   and m["standard"] == "narrow"), None)
    wide = next((m for m in the_map if m["parameter"].startswith("kappa")
                 and m["standard"] == "wide"), None)
    crossover = _crossover()

    if narrow and narrow["identifiable_fraction"] >= CR.MAP_PARTIAL:
        verdict = "TRUST_IS_MEASURABLE_OVER_PART_OF_ITS_RANGE"
    elif wide and wide["identifiable_fraction"] >= CR.MAP_PARTIAL:
        verdict = "TRUST_IS_MEASURABLE_ONLY_UNDER_THE_WIDE_STANDARD"
    else:
        verdict = "TRUST_IS_NOT_MEASURABLE_UNDER_EITHER_STANDARD"

    payload = {
        "check": "R-6 / R-8a",
        "question": ("Fitted to what the reader produces rather than to what it was shown, which "
                     "parameters are measurable, and over what range?"),
        "plain_language": (
            "To measure something about a reader you have to look at what the reader does, not at "
            "what it was shown. The earlier pass looked at what it was shown, which is why trust "
            "came back unmeasurable. Fitted properly, trust is measurable up to a point and then "
            "stops mattering: past that point two readers with different trust behave identically, "
            "so there is nothing left to measure. That is a fact about the model rather than a "
            "limit on the measurement."),
        "criteria": {"observability": list(CR.OBSERVABILITY),
                     "primary_in_prose": CR.OBSERVABILITY_PRIMARY,
                     "identifiable_se": CR.IDENTIFIABLE_SE},
        "correction_to_the_earlier_pass": (
            "the diagnostics pass fitted trust to the observation tape, which the world generates "
            "and which contains no trust parameter. Its UNIDENTIFIABLE verdict answered the wrong "
            "question and is superseded here. The original verdict is retained in "
            "results/diagnostics/p1_recovery.json."),
        "channel_crossover": crossover,
        "recovery": rows,
        "identifiability_map": the_map,
        "verdict": verdict,
    }
    payload["statement"] = _statement(payload, narrow, wide, crossover)
    (repair_dir() / "r6_estimators.json").write_text(
        json.dumps(payload, indent=2, default=float), encoding="utf-8")
    return payload


def _crossover() -> float:
    from ..diagnostics import diagnostics_dir
    p = diagnostics_dir() / "d1_channels.json"
    if not p.exists():
        return float("nan")
    return float(json.loads(p.read_text(encoding="utf-8")).get("crossover_kappa", float("nan")))


def _statement(p: dict, narrow, wide, crossover) -> str:
    bits = ["**The earlier verdict was wrong and it was mine.** Trust looked unidentifiable "
            "because it was fitted to the observation tape, and the tape is generated by the "
            "world, which contains no trust parameter. Fitted to what the reader itself produces, "
            "it recovers."]
    if narrow:
        bits.append(
            "**Under the narrow standard**, what the reader does and says, trust is identifiable "
            "over %.0f%% of the swept range, from %.2f to %.2f, and saturates above that. Above "
            "the saturation point readers with different trust are behaviourally identical: same "
            "engagement, same answer, every time."
            % (100 * narrow["identifiable_fraction"], narrow["identifiable_from"],
               narrow["identifiable_to"]))
    if wide:
        bits.append(
            "**Under the wide standard**, which additionally lets the reader report graded "
            "confidence, it is identifiable over %.0f%% of the range. The pair brackets what any "
            "real reporting process could deliver: the narrow figure is a floor and the wide one a "
            "ceiling." % (100 * wide["identifiable_fraction"]))
    if np.isfinite(crossover) and narrow:
        bits.append(
            "**The saturation point is not arbitrary.** The channel-accounting check locates, in "
            "closed form, the trust level at which the label's evidence per glance overtakes the "
            "work's: %.3f. Above it the label has already won and additional trust has nothing "
            "left to change, which is exactly where behaviour stops varying. Saturation is what a "
            "parameter looks like once it has won its argument.\n\n"
            "**The consequence is uncomfortable and it should be said plainly.** The model's "
            "default trust sits ABOVE that point. So at the setting every headline experiment "
            "runs, trust is not a measurable quantity even in principle, and claims of the form "
            "'a reader with this much trust does X' are stipulations rather than measurements at "
            "that setting. What remains sayable, and is observable, is ordinal: this reader is in "
            "the regime where the label dominates the work." % crossover)
    bits.append(
        "**And it gives a human study its design.** Do not try to measure trust directly, and do "
        "not run the study with content where the label overwhelms what is on the page: everyone "
        "looks the same there and nothing is learned. Run it where the work can argue back, which "
        "is the only regime in which individual differences in trust have observable consequences.")
    rest = [m for m in p["identifiability_map"] if not m["parameter"].startswith("kappa")]
    if rest:
        bits.append("**The rest of the map**, carried forward unchanged because their estimators "
                    "did not change: "
                    + "; ".join("%s is %s (%.0f%% of its range), fitted to %s"
                                % (m["parameter"], m["reading"],
                                   100 * m["identifiable_fraction"], m["fitted_to"])
                                for m in rest)
                    + ". The distinction between fitting to the reader and fitting to an analyst's "
                      "model is not decoration: the second asks whether a value is identifiable in "
                      "principle, which is strictly easier, and for readability that gap is the "
                      "whole version 4 reframe.")
    return "\n\n".join(bits)
