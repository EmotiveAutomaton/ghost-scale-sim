"""The repair pass: from demonstration to measurement.

WHAT THE DIAGNOSTICS PASS ACTUALLY FOUND, stated once here because it is the governing fact.

This apparatus was built to DEMONSTRATE and is now being audited as though it MEASURES. Those have
different standards and most of what came back is the gap between them. The evidence is direct:
trust looked unidentifiable because nothing in the model was ever built to estimate trust, and the
two parameters that recovered cleanly recovered because somebody wrote an estimator for them during
the diagnostics pass. They had none before either.

THE RULE THIS PASS WORKS UNDER. Every change either makes something measurable that was not, or
removes something. The model has grown every version since version 1 and nothing has ever been taken
out, and that accretion is what produced a construction where two of the interior peak's
dependencies could not be broken because the model refuses to run without them. A repair pass that
adds machinery in the ordinary way makes that worse.

-----------------------------------------------------------------------------------------
THREE CORRECTIONS THE PASS MADE TO ITS OWN SPECIFICATION, all before any repair ran.

1. The specification's error-reduction formula is undefined as written. Compared against a point
   mass on the truth, every term diverges; floored at an epsilon it returns a number that tracks the
   epsilon rather than the data. The arguments have to be the other way round. See
   ``metrics.error_reduction``.

2. Recomputing the under-powered criteria over per-reader pairs answers a DIFFERENT question rather
   than the same one at higher power, and answers it worse. Within cells the two quantities are
   uncorrelated, so pooling readers attenuates rather than sharpens. The estimand is preserved by
   bootstrapping the cell means. Both are reported, labelled.

3. Trust is not structurally unidentifiable. The diagnostics pass fitted it to the observation tape,
   and the observations are generated by the world, which contains no trust parameter. Fitted to the
   reader's own behaviour it recovers, and where it stops recovering it stops for a reason that is a
   fact about the model rather than a limit on measurement. See ``r6_estimators``.

-----------------------------------------------------------------------------------------
WHAT IS OBSERVABLE, WHICH IS A MODELLING CHOICE AND IS MADE EXPLICITLY.

Recovering a reader's parameters means fitting them to something the reader produces. Two standards
are defensible and they give different answers, so both are run and the pair is reported as a
bracket:

  NARROW  what the reader DOES: how long it keeps looking, and what it says the work was for.
          The conservative standard, and what an experiment on a person straightforwardly collects.
  WIDE    the same, plus a graded report of how sure it is across every possible purpose.
          Common in judgment research, and it assumes perfect introspective access, which is a
          strong assumption sitting uncomfortably close to what this framework is about.

Real readers are between the two. Narrow is a floor on what is measurable and wide is a ceiling, so
the pair brackets the truth, and the useful output is an IDENTIFIABILITY MAP: for each parameter,
the range over which it is a measured quantity and the range over which it is a free choice.
"""
from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
REPAIR_DIR = REPO_ROOT / "results" / "repair"
FIG_DIR = REPO_ROOT / "figures" / "repair"


def repair_dir(sub: str | None = None) -> Path:
    p = REPAIR_DIR if sub is None else REPAIR_DIR / sub
    p.mkdir(parents=True, exist_ok=True)
    return p


def figures_dir() -> Path:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    return FIG_DIR
